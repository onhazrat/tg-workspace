def _predecessor(session: Session, owner: uuid.UUID) -> tuple[Summary, str]:
    """A Summary whose successor window holds two Posts, one per hour ago."""
    now = int(time.time() * 1000)
    channel = f"cov-{uuid.uuid4().hex[:8]}"
    for post_id, ago in ((1, 3_000_000), (2, 1_200_000)):
        session.add(
            Post(channel_name=channel, post_id=post_id, text="p", timestamp=now - ago)
        )
    follow_channels(session, channel, user_id=owner)
    row = Summary(
        id=f"sum-{uuid.uuid4().hex[:8]}",
        user_id=owner,
        text="body",
        scope=stored_scope(
            channels=[channel], start=now - 7_200_000, end=now - 3_600_000
        ),
        language="English",
        post_count=0,
        timestamp=now,
        extra={"autoRegenerate": True},
    )
    session.add(row)
    session.commit()
    return row, channel


def _covered(owner: uuid.UUID, summary_id: str) -> tuple[list[tuple[str, int]], int]:
    with Session(engine) as check:
        scope = get_summary(check, summary_id, user_id=owner)["scope"]
    refs = sorted((r["channelName"], r["postId"]) for r in scope["posts"] or [])
    return refs, scope["scopedPostCount"]


def test_the_scheduler_records_the_posts_it_regenerated_from(
    session: Session, user: User
) -> None:
    predecessor, channel = _predecessor(session, user.id)

    new_id = asyncio.run(
        auto_summary._regenerate_one(session, predecessor, owner_id=user.id)
    )

    assert new_id is not None
    assert _covered(user.id, new_id) == ([(channel, 1), (channel, 2)], 2)


def test_a_browser_regeneration_records_them_when_its_attempt_starts(
    session: Session, user: User
) -> None:
    predecessor, channel = _predecessor(session, user.id)
    new_id = f"sum-{uuid.uuid4().hex[:8]}"
    submit_summary(
        session,
        user_id=user.id,
        summary_id=new_id,
        derived_from=SummaryDerivation(summaryId=predecessor.id, mode="successor"),
    )

    # No Key, so the Attempt is refused, after the prompt and its refs are kept.
    summary_generation.start_attempt(
        session, new_id, user_id=user.id, model=None, key_id=None, temperature=None
    )

    assert _covered(user.id, new_id) == ([(channel, 1), (channel, 2)], 2)


def _prompt_of(summary_id: str) -> str:
    with Session(engine) as check:
        payload = check.get(SummaryPayload, summary_id)
        assert payload is not None and payload.prompt_text
        return payload.prompt_text


def test_the_scheduler_and_the_browser_build_one_prompt_for_one_successor(
    session: Session, user: User
) -> None:
    """One predecessor, regenerated by the scheduler and by `derivedFrom`.

    The two doors built different prompts for the same successor: the
    scheduler read every Post of the Channels itself and formatted them
    without the media hints (ADR-038). Both now build through `start_attempt`,
    so the stored prompts are byte-identical. Replaces the old API parity
    test of the scheduler's `scope` body, a path that no longer exists.
    """
    predecessor, channel = _predecessor(session, user.id)
    now = int(time.time() * 1000)
    session.add(
        Post(
            channel_name=channel,
            post_id=3,
            text="with a photo",
            timestamp=now - 2_000_000,
            media={"kinds": ["photo"]},
        )
    )
    session.commit()
    browser_id = f"sum-{uuid.uuid4().hex[:8]}"
    submit_summary(
        session,
        user_id=user.id,
        summary_id=browser_id,
        derived_from=SummaryDerivation(summaryId=predecessor.id, mode="successor"),
    )
    summary_generation.start_attempt(
        session, browser_id, user_id=user.id, model=None, key_id=None, temperature=None
    )

    scheduled_id = asyncio.run(
        auto_summary._regenerate_one(session, predecessor, owner_id=user.id)
    )

    assert scheduled_id is not None
    browser = _prompt_of(browser_id)
    assert "Media: photo" in browser
    assert _prompt_of(scheduled_id) == browser


def test_a_scheduled_window_with_no_posts_says_so_and_starts_no_attempt(
    session: Session, user: User
) -> None:
    predecessor, channel = _predecessor(session, user.id)
    session.exec(delete(Post).where(col(Post.channel_name) == channel))
    session.commit()

    new_id = asyncio.run(
        auto_summary._regenerate_one(session, predecessor, owner_id=user.id)
    )

    assert new_id is not None
    with Session(engine) as check:
        successor = get_summary(check, new_id, user_id=user.id)
        assert successor["text"].startswith("No new posts found")
        assert "status" not in successor
        assert last_attempt(check, new_id) is None


def test_a_scheduled_window_past_the_post_limit_ends_failed_with_why(
    session: Session, user: User, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(artifact_coverage, "MAX_PROMPT_POSTS", 1)
    predecessor, _ = _predecessor(session, user.id)

    new_id = asyncio.run(
        auto_summary._regenerate_one(session, predecessor, owner_id=user.id)
    )

    assert new_id is not None
    with Session(engine) as check:
        assert get_summary(check, new_id, user_id=user.id)["status"] == "failed"
        attempt = last_attempt(check, new_id)
        assert attempt is not None and attempt.outcome == "failed"
        assert "more than the 1 a single prompt" in (attempt.error or "")


def test_a_prompt_keeps_its_missing_post_count_and_a_successor_does_not(
    session: Session, user: User
) -> None:
    """The count sits beside the prompt it describes (ADR-038)."""
    predecessor, channel = _predecessor(session, user.id)
    now = int(time.time() * 1000)
    summary_id = f"sum-{uuid.uuid4().hex[:8]}"
    submit_summary(
        session,
        user_id=user.id,
        summary_id=summary_id,
        submission=ScopeSubmission.model_validate(
            {
                "channels": [channel],
                "window": {"mode": "fixed", "start": 0, "end": now - 60_000},
            }
        ),
    )
    # Reclaimed after the freeze.
    session.exec(delete(Post).where(col(Post.channel_name) == channel))
    session.commit()

    summary_generation.start_attempt(
        session, summary_id, user_id=user.id, model=None, key_id=None, temperature=None
    )
    predecessor.extra = {**(predecessor.extra or {}), "missingPosts": 2}
    session.add(predecessor)
    session.commit()
    successor = asyncio.run(
        auto_summary._regenerate_one(session, predecessor, owner_id=user.id)
    )

    with Session(engine) as check:
        assert get_summary(check, summary_id, user_id=user.id)["missingPosts"] == 2
        assert successor is not None
        assert "missingPosts" not in get_summary(check, successor, user_id=user.id)


def test_a_browser_regeneration_of_an_empty_window_says_so_as_the_scheduler_does(
    session: Session, user: User
) -> None:
    """The server's Covered Posts decide emptiness for both doors (ADR-038).

    The browser used to count the window itself and write its own "no new
    posts" text and Post count over the server's.
    """
    predecessor, channel = _predecessor(session, user.id)
    session.exec(delete(Post).where(col(Post.channel_name) == channel))
    session.commit()
    browser_id = f"sum-{uuid.uuid4().hex[:8]}"
    submit_summary(
        session,
        user_id=user.id,
        summary_id=browser_id,
        derived_from=SummaryDerivation(summaryId=predecessor.id, mode="successor"),
        # The browser opens its successor Failed, as Generate does.
        extra={"status": "failed"},
    )

    started = summary_generation.start_attempt(
        session, browser_id, user_id=user.id, model=None, key_id=None, temperature=None
    )
    scheduled_id = asyncio.run(
        auto_summary._regenerate_one(session, predecessor, owner_id=user.id)
    )

    assert started is None
    assert scheduled_id is not None
    with Session(engine) as check:
        browser = get_summary(check, browser_id, user_id=user.id)
        scheduled = get_summary(check, scheduled_id, user_id=user.id)
        assert browser["text"].startswith("No new posts found")
        assert browser["text"] == scheduled["text"]
        assert browser["postCount"] == 0
        assert "status" not in browser
        assert last_attempt(check, browser_id) is None


def test_both_doors_describe_the_channels_by_the_accounts_bio_and_tags_setting(
    session: Session, user: User
) -> None:
    """The Channels block is the server's, read from the Account's setting.

    The browser used to send its own `channelsText` on Generate and nothing
    on a regeneration, so the two prompts differed whenever a switch was on.
    A Channel's tags are the Account's own, never another Account's.
    """
    predecessor, channel = _predecessor(session, user.id)
    row = session.exec(select(Channel).where(col(Channel.name) == channel)).one()
    row.bio = "  Daily wire news.  "
    session.add(row)
    other = create_random_user(session)
    assign_tag(session, user_id=user.id, name="Politics", handles=[channel])
    assign_tag(session, user_id=other.id, name="Foreign", handles=[channel])
    session.commit()
    put_user_setting(
        session,
        AI_PREFS_KEY,
        {"includeChannelBio": True, "includeChannelTags": True},
        user_id=user.id,
    )
    browser_id = f"sum-{uuid.uuid4().hex[:8]}"
    submit_summary(
        session,
        user_id=user.id,
        summary_id=browser_id,
        derived_from=SummaryDerivation(summaryId=predecessor.id, mode="successor"),
    )
    summary_generation.start_attempt(
        session, browser_id, user_id=user.id, model=None, key_id=None, temperature=None
    )

    scheduled_id = asyncio.run(
        auto_summary._regenerate_one(session, predecessor, owner_id=user.id)
    )

    assert scheduled_id is not None
    browser = _prompt_of(browser_id)
    assert f"### {channel}\nBio: Daily wire news.\nCurrent tags: Politics" in browser
    assert "Foreign" not in browser
    assert _prompt_of(scheduled_id) == browser
    session.exec(delete(User).where(col(User.id) == other.id))
    session.commit()
